# 날짜별 가동 수량 계산
operation_counts = defaultdict(int)
date_pattern = re.compile(r'(\d{4}/\d{2}/\d{2})')

for log in ebam_logs:
    # 날짜 추출
    date_match = date_pattern.search(log)
    if date_match:
        date = date_match.group(1)
        operation_counts[date] += 1

# 결과 출력
print('=== (PM-2.5) E-BAM 날짜별 가동 수량 분석 ===')
print(f'총 분석 기간: {min(operation_counts.keys())} ~ {max(operation_counts.keys())}')
print()

# Top 5 기간 찾기
sorted_by_count = sorted(operation_counts.items(), key=lambda x: x[1], reverse=True)
print('Top 5 가동 수량 기간:')
for i, (date, count) in enumerate(sorted_by_count[:5], 1):
    print(f'{i}. {date}: {count}대 가동')

